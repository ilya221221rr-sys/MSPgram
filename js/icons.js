// Заменяет содержимое элементов [data-ic="имя"] на SVG
export function mountIcons(root = document) {
  root.querySelectorAll('[data-ic]').forEach((n) => {
    n.innerHTML = icon(n.dataset.ic, Number(n.dataset.icSize) || 20);
  });
}
